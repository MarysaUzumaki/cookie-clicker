BONUS_PER_COOKIE = 0.1


def pick_rarity(rng):
    return rng.choices(RARITIES, weights=RARITY_WEIGHTS, k=1)[0]


def flavor(rng):
    t = rng.choice(FLAVOR_TEMPLATES)
    return t.replace("{z}", rng.choice(FILLERS))


def make_names(k, seed=42):
    """Стабильная перестановка уникальных комбинаций прилагательное×существительное."""
    rng = random.Random(seed)
    adi = list(dict.fromkeys(ADJECTIVES))  # дедупликация с сохранением порядка
    nouns = list(dict.fromkeys(NOUNS))
    combos = [f"{a} {n}" for a in adi for n in nouns]
    if len(combos) < k:
        raise ValueError(f"Не хватает комбинаций имён: {len(combos)} < {k}")
    rng.shuffle(combos)
    return combos[:k]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--count", type=int, required=True)
    ap.add_argument("--base", type=float, default=40.0)
    ap.add_argument("--top", type=float, default=1e18)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--bonus", type=float, default=BONUS_PER_COOKIE)
    args = ap.parse_args()

    names = make_names(args.count)
    ratio = (args.top / args.base) ** (1.0 / max(1, args.count - 1))

    lines = []
    for i in range(args.count):
        rng = random.Random(1000 + i)  # детерминированно, независимо от строки
        rarity = pick_rarity(rng)
        base = args.base * (ratio ** i)
        value = int(base * RARITY_MULT[rarity] * rng.uniform(0.9, 1.15))
        entry = {
            "id": str(i + 1),
            "name": names[i],
            "rarity": rarity,
            "value": value,
            "bonus": round(args.bonus, 3),
            "flavor": flavor(rng),
        }
        lines.append(json.dumps(entry, ensure_ascii=False))

    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Сгенерировано {len(lines)} печений -> {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()